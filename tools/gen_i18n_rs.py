"""Generates rust/zerotag-ui/src/i18n_strings.rs from tools/i18n_strings.tsv (French, English, Japanese, Simplified Chinese)."""
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
items = []
for n, line in enumerate((root / "tools/i18n_strings.tsv").read_text(encoding="utf-8").splitlines(), 1):
    if not line or line.startswith("#"):
        continue
    fields = line.split("\t")
    if len(fields) != 5 or not all(fields[1:]):
        sys.exit(f"tools/i18n_strings.tsv:{n}: expected a name and four non-empty translations")
    name, texts = fields[0], fields[1:]
    if len({t.count("%") for t in texts}) != 1:
        sys.exit(f"placeholders differ in {name}: {texts}")
    items.append((name, texts))
if len({n for n, _ in items}) != len(items):
    sys.exit("duplicate string name")

def rs(s):
    import json
    return json.dumps(s, ensure_ascii=False)

out = ["// SPDX-License-Identifier: MIT",
       "// Generated by tools/gen_i18n_rs.py from tools/i18n_strings.tsv. Do not edit by hand.", "",
       "#[derive(Clone, Copy, Debug, PartialEq, Eq)]", "pub enum Str {"]
out += [f"    {n}," for n, _ in items]
out += ["}", "", f"pub const COUNT: usize = {len(items)};", "",
        "/// Indexed by `Str as usize`: [French, English, Japanese, Simplified Chinese].",
        "pub static TABLE: [[&str; 4]; COUNT] = ["]
out += [f"    [{', '.join(rs(x) for x in t)}]," for _, t in items]
out += ["];", ""]
(root / "rust/zerotag-ui/src/i18n_strings.rs").write_text("\n".join(out), encoding="utf-8")
print(len(items), "strings")
