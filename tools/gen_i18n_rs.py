"""Generates rust/zerotag-ui/src/i18n_strings.rs from src/app/i18n_strings.def (French, English, Japanese; the C++ table)
and tools/i18n_zh_hans.tsv (Simplified Chinese, Rust port only)."""
import json, re, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "src/app/i18n_strings.def").read_text(encoding="utf-8")
items = []
for line in src.splitlines():
    m = re.match(r"\s*X\(\s*(\w+)\s*,(.*)\)\s*$", line)
    if not m:
        continue
    strings = re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(2))
    if len(strings) != 3:
        sys.exit(f"bad line: {line}")
    items.append((m.group(1), [json.loads('"' + s + '"') for s in strings]))

zh = {}
for line in (root / "tools/i18n_zh_hans.tsv").read_text(encoding="utf-8").splitlines():
    if line and not line.startswith("#"):
        name, text = line.split("\t", 1)
        zh[name] = text
missing = [n for n, _ in items if n not in zh]
if missing:
    sys.exit(f"no Simplified Chinese for: {missing}")
for n, t in items:
    t.append(zh[n])
    if len({x.count("%") for x in t}) != 1:
        sys.exit(f"placeholders differ in {n}: {t}")

def rs(s):
    return json.dumps(s, ensure_ascii=False)

out = ["// SPDX-License-Identifier: MIT",
       "// Generated by tools/gen_i18n_rs.py from src/app/i18n_strings.def. Do not edit by hand.", "",
       "#[derive(Clone, Copy, Debug, PartialEq, Eq)]", "pub enum Str {"]
out += [f"    {n}," for n, _ in items]
out += ["}", "", f"pub const COUNT: usize = {len(items)};", "",
        "/// Indexed by `Str as usize`: [French, English, Japanese, Simplified Chinese].",
        "pub static TABLE: [[&str; 4]; COUNT] = ["]
out += [f"    [{rs(t[0])}, {rs(t[1])}, {rs(t[2])}, {rs(t[3])}]," for _, t in items]
out += ["];", ""]
(root / "rust/zerotag-ui/src/i18n_strings.rs").write_text("\n".join(out), encoding="utf-8")
print(len(items), "strings")
